import 'package:flutter_test/flutter_test.dart';
import 'package:flutter_ai_agent_sdk/flutter_ai_agent_sdk.dart';

void main() {
  group('TEST-AI-U: Functional Model & Parsing Tests', () {
    test('TEST-AI-U01: Should parse QuickReplyOption with pipe syntax accurately', () {
      const raw = 'Jakarta, Bangkok|Bangkok Private Office, KL|Kuala Lumpur Hub';
      final options = QuickReplyOption.parseList(raw);

      expect(options.length, equals(3));
      expect(options[0].label, equals('Jakarta'));
      expect(options[0].value, equals('Jakarta'));

      expect(options[1].label, equals('Bangkok'));
      expect(options[1].value, equals('Bangkok Private Office'));

      expect(options[2].label, equals('KL'));
      expect(options[2].value, equals('Kuala Lumpur Hub'));
    });

    test('TEST-AI-U02: Should parse CardPayload from HTML generated by CRM Card Builder', () {
      const html =
          "<div class='card'><div class='card-title'>Axiata Tower (KL) - Private Office</div><div class='small'>Our private offices are available on flexible terms.<br/><br/>Explore this space in detail here: https://www.ceosuite.com/locations/axiata</div></div><div class='cta-note'>Booking starts from \$15/hour</div>";

      final card = CardPayload.parseFromHtmlOrText(html);

      expect(card, isNotNull);
      expect(card!.title, equals('Axiata Tower (KL) - Private Office'));
      expect(card.description, contains('flexible terms'));
      expect(card.linkUrl, equals('https://www.ceosuite.com/locations/axiata'));
      expect(card.ctaNote, equals('Booking starts from \$15/hour'));
      expect(card.actionLabel, isNull);
      expect(card.bannerTitle, isNull);
    });

    test('TEST-AI-U02B: Should parse actionLabel and bannerTitle from HTML and JSON', () {
      const html =
          "<div class='card'><div class='card-banner'>Promo Eksklusif</div><div class='card-title'>Sahid Sudirman Hub</div><div class='small'>Kantor siap pakai.<br/>https://www.ceosuite.com/sahid</div><div class='card-action'>Lihat Info Lengkap</div></div>";

      final card = CardPayload.parseFromHtmlOrText(html);
      expect(card, isNotNull);
      expect(card!.title, equals('Sahid Sudirman Hub'));
      expect(card.bannerTitle, equals('Promo Eksklusif'));
      expect(card.actionLabel, equals('Lihat Info Lengkap'));

      // From JSON
      final jsonCard = CardPayload.fromJson({
        'title': 'One Pacific Place',
        'description': 'Luxury serviced office',
        'url': 'https://ceosuite.com/opp',
        'buttonText': 'Explore Space',
        'headerTitle': 'Prime Venue',
      });
      expect(jsonCard.title, equals('One Pacific Place'));
      expect(jsonCard.actionLabel, equals('Explore Space'));
      expect(jsonCard.bannerTitle, equals('Prime Venue'));
    });

    test('TEST-AI-U03: Should parse FormPayload from HTML generated by CRM Form Builder', () {
      const html =
          "Silakan lengkapi form berikut:<form class='form-card' onsubmit=\"event.preventDefault(); fetch('https://n8n.example.com/webhook/test', {method:'POST'});\"><label class='form-card_label'>Full Name <span class=\"required\">*</span></label><input type='text' name='full_name' placeholder='e.g. John Doe' required/><label class='form-card_label'>WhatsApp Number</label><input type='tel' name='whatsapp' placeholder='0812345678'/><button type='submit'>Submit</button></form>";

      final form = FormPayload.parseFromHtml(html);

      expect(form, isNotNull);
      expect(form!.introMessage, contains('Silakan lengkapi form'));
      expect(form.webhookUrl, equals('https://n8n.example.com/webhook/test'));
      expect(form.fields.length, greaterThanOrEqualTo(2));
      expect(form.fields[0].label, equals('Full Name'));
      expect(form.fields[0].required, isTrue);
    });

    test('TEST-AI-U04: Should auto-detect [HANDOFF_REQUESTED] tag and switch to agent', () {
      const rawReply =
          'Mohon tunggu sebentar, saya sedang menghubungkan Anda dengan representatif CEO Suite... [HANDOFF_REQUESTED]';

      final msg = ChatMessage.fromApiResponse(
        id: 'msg_001',
        rawReply: rawReply,
      );

      expect(msg.isHandoff, isTrue);
      expect(msg.sender, equals(MessageSender.agent));
      expect(msg.text, isNot(contains('[HANDOFF_REQUESTED]')));
      expect(msg.text, contains('menghubungkan Anda'));
    });

    test('TEST-AI-U05: Should handle ResponseType fallback safely on unknown string', () {
      expect(ResponseType.fromString('card'), equals(ResponseType.card));
      expect(ResponseType.fromString('options'), equals(ResponseType.options));
      expect(ResponseType.fromString('form'), equals(ResponseType.form));
      expect(ResponseType.fromString('handoff'), equals(ResponseType.handoff));
      expect(ResponseType.fromString('invalid_type'), equals(ResponseType.text));
      expect(ResponseType.fromString(null), equals(ResponseType.text));
    });

    test('TEST-AI-U06: Should parse real CRM centre card HTML into clean markdown without raw tags', () {
      const html =
          "<div class='card'><div class='card-title'>Vietcombank Tower (Ho Chi Minh City) - Meeting Room</div><div class='small'><b>Address:</b> Level 21, No. 5 Me Linh Square, Ben Nghe Ward, District 1, Ho Chi Minh City 70000, Vietnam<br/><b>Phone:</b> +84 (28) 3827 1988 | <b>WhatsApp:</b> <a href='https://wa.me/84837048668'>+84 83 704 8668</a><br/><b>Transport:</b> Prime District 1 waterfront location on Me Linh Square, near Bach Dang pier.<br/><b>Facilities:</b> Grade A Waterfront Tower, 24/7 Member Access, Executive Boardrooms, High-Speed Wi-Fi, Reception Concierge, Mail & Parcel Handling.<br/><br/>Explore space details: <a href='https://www.ceosuite.com/locations/ho-chi-minh-vietcombank-tower/' target='_blank'>https://www.ceosuite.com/locations/ho-chi-minh-vietcombank-tower/</a></div></div><div class='cta-note'>Have a question about this location? Select an option below or type your inquiry anytime.</div>";

      final card = CardPayload.parseFromHtmlOrText(html);
      expect(card, isNotNull);
      expect(card!.title, equals('Vietcombank Tower (Ho Chi Minh City) - Meeting Room'));
      expect(card.linkUrl, equals('https://www.ceosuite.com/locations/ho-chi-minh-vietcombank-tower/'));

      // Check description is clean Markdown without raw tags
      expect(card.description, contains('**Address:**'));
      expect(card.description, contains('**Phone:**'));
      expect(card.description, contains('**WhatsApp:**'));
      expect(card.description, contains('[+84 83 704 8668](https://wa.me/84837048668)'));
      expect(card.description, isNot(contains('<div')));
      expect(card.description, isNot(contains('<b>')));
      expect(card.description, isNot(contains('</b>')));
      expect(card.description, isNot(contains('<br')));
      expect(card.description, isNot(contains('<a href')));

      // Check ctaNote is clean
      expect(card.ctaNote, equals('Have a question about this location? Select an option below or type your inquiry anytime.'));
    });

    test('TEST-AI-U07: Should parse Front Desk reception card with WhatsApp cleanly', () {
      const html =
          '<div class="card"><div class="card-title">Front Desk &amp; Reception - Axiata Tower</div><div class="small"><b>Address:</b> 27th Floor, KL Sentral<br/><b>WhatsApp:</b> <a href="https://wa.me/60123608913">+60 12 360 8913</a><br/><b>Reception Hours:</b> Mon - Fri</div></div>';

      final card = CardPayload.parseFromHtmlOrText(html);
      expect(card, isNotNull);
      expect(card!.title, equals('Front Desk & Reception - Axiata Tower'));
      expect(card.description, contains('**Address:** 27th Floor, KL Sentral'));
      expect(card.description, contains('**WhatsApp:** [+60 12 360 8913](https://wa.me/60123608913)'));
      expect(card.description, contains('**Reception Hours:** Mon - Fri'));
      expect(card.description, isNot(contains('<')));
    });

    test('TEST-AI-U08: Should convert HTML FAQ reply to clean markdown via ChatMessage.fromApiResponse', () {
      const rawFaq =
          '<b>What is a Serviced Office?</b><br/><br/>Also known as managed offices, serviced offices provide:<br/>• <b>Plug & Play:</b> Ready to move in.<br/>• <b>All-Inclusive:</b> Utilities included.<br/><br/>Explore: <a href="https://www.ceosuite.com">CEO SUITE</a>';

      final msg = ChatMessage.fromApiResponse(
        id: 'faq_01',
        rawReply: rawFaq,
        responseType: 'options',
        rawOptions: ['Book Tour', 'Contact Us'],
      );

      expect(msg.type, equals(ResponseType.options));
      expect(msg.text, contains('**What is a Serviced Office?**'));
      expect(msg.text, contains('• **Plug & Play:** Ready to move in.'));
      expect(msg.text, contains('• **All-Inclusive:** Utilities included.'));
      expect(msg.text, isNot(contains('<b>')));
      expect(msg.text, isNot(contains('</b>')));
      expect(msg.text, isNot(contains('<br')));
      expect(msg.options.length, equals(2));
    });
  });
}
