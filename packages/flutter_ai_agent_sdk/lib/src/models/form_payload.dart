/// Single field definition inside a dynamic Lead Capture Form.
class LeadFormField {
  final String name;
  final String label;
  final String type; // text, email, tel, number, date, textarea, select
  final String placeholder;
  final bool required;

  /// Choices of a `select` field (empty for every other type).
  final List<String> options;

  const LeadFormField({
    required this.name,
    required this.label,
    this.type = 'text',
    this.placeholder = '',
    this.required = false,
    this.options = const [],
  });

  factory LeadFormField.fromJson(Map<String, dynamic> json) {
    return LeadFormField(
      name: json['name'] ?? '',
      label: json['label'] ?? '',
      type: json['type'] ?? 'text',
      placeholder: json['placeholder'] ?? '',
      required: json['required'] == true,
      options: (json['options'] as List?)?.map((o) => o.toString()).toList() ??
          const [],
    );
  }

  Map<String, dynamic> toJson() => {
        'name': name,
        'label': label,
        'type': type,
        'placeholder': placeholder,
        'required': required,
        if (options.isNotEmpty) 'options': options,
      };
}

/// Payload for an interactive Lead Capture Form.
class FormPayload {
  final String introMessage;
  final List<LeadFormField> fields;
  final String? webhookUrl;

  /// Text of the submit button (the CRM Form Builder emits "Submit").
  final String submitLabel;

  const FormPayload({
    required this.introMessage,
    required this.fields,
    this.webhookUrl,
    this.submitLabel = 'Submit',
  });

  factory FormPayload.fromJson(Map<String, dynamic> json) {
    final fieldsRaw = json['fields'] as List? ?? [];
    return FormPayload(
      introMessage: json['introMessage'] ?? 'Please fill out the form below:',
      fields: fieldsRaw.map((f) => LeadFormField.fromJson(Map<String, dynamic>.from(f))).toList(),
      webhookUrl: json['webhookUrl'],
      submitLabel: json['submitLabel'] ?? 'Submit',
    );
  }

  // `<label class='form-card_label'>Name <span class="required">*</span></label>`
  static final RegExp _labelRe = RegExp(
    r'<label\b[^>]*>(.*?)</label>',
    caseSensitive: false,
    dotAll: true,
  );

  // The control that follows a label: <input ...>, <textarea ...> or <select ...>.
  static final RegExp _controlRe = RegExp(
    r'<(input|textarea|select)\b([^>]*)>',
    caseSensitive: false,
  );

  static final RegExp _optionRe = RegExp(
    r'<option\b([^>]*)>(.*?)</option>',
    caseSensitive: false,
    dotAll: true,
  );

  static final RegExp _submitButtonRe = RegExp(
    r'''<button\b[^>]*type\s*=\s*['"]submit['"][^>]*>(.*?)</button>''',
    caseSensitive: false,
    dotAll: true,
  );

  static final RegExp _webhookRe = RegExp(
    r'''fetch\(\s*['"](https?://[^'"]+)['"]''',
    caseSensitive: false,
  );

  static String? _attr(String attrs, String name) {
    final m = RegExp(
      '\\b$name\\s*=\\s*(?:"([^"]*)"|\'([^\']*)\'|([^\\s>/]+))',
      caseSensitive: false,
    ).firstMatch(attrs);
    if (m == null) return null;
    return m.group(1) ?? m.group(2) ?? m.group(3);
  }

  /// A bare `required` attribute (with or without a value), not `data-required`.
  static bool _hasRequired(String attrs) =>
      RegExp(r'(?:^|\s)required(?=[\s=/>]|$)', caseSensitive: false).hasMatch(attrs);

  static String _text(String html) => html
      .replaceAll(RegExp(r'<[^>]*>'), '')
      .replaceAll('&nbsp;', ' ')
      .replaceAll('&amp;', '&')
      .replaceAll('&lt;', '<')
      .replaceAll('&gt;', '>')
      .replaceAll('&quot;', '"')
      .replaceAll('&#39;', "'")
      .trim();

  /// Parses form definition from HTML generated by CRM Form Builder.
  static FormPayload? parseFromHtml(String html) {
    if (!html.contains("class='form-card'") && !html.contains('class="form-card"')) {
      return null;
    }

    // Extract intro message before the <form> tag
    final formIdx = html.indexOf('<form');
    String intro = formIdx > 0 ? html.substring(0, formIdx).trim() : 'Silakan lengkapi form berikut:';
    intro = _text(intro);

    // Extract webhook URL
    final webhookUrl = _webhookRe.firstMatch(html)?.group(1);

    final fields = <LeadFormField>[];
    final labels = _labelRe.allMatches(html).toList();
    for (var i = 0; i < labels.length; i++) {
      final label = labels[i];
      // Look for this label's control only up to the next label.
      final end = i + 1 < labels.length ? labels[i + 1].start : html.length;
      final control = _controlRe.firstMatch(html.substring(label.end, end));
      if (control == null) continue;

      final tag = control.group(1)!.toLowerCase();
      final attrs = control.group(2) ?? '';
      final labelText = _text(label.group(1) ?? '');
      if (labelText.isEmpty) continue;

      final type = tag == 'input' ? (_attr(attrs, 'type') ?? 'text').toLowerCase() : tag;
      var options = const <String>[];
      if (tag == 'select') {
        final selectEnd = html.indexOf('</select>', label.end + control.start);
        final body = selectEnd == -1
            ? ''
            : html.substring(label.end + control.end, selectEnd);
        options = _optionRe
            .allMatches(body)
            .map((m) => _text(m.group(2) ?? ''))
            .where((o) => o.isNotEmpty)
            .toList();
      }

      fields.add(LeadFormField(
        name: _attr(attrs, 'name') ?? labelText.toLowerCase(),
        label: labelText.replaceAll(RegExp(r'\s*\*$'), '').trim(),
        type: type,
        placeholder: _text(_attr(attrs, 'placeholder') ?? ''),
        required: _hasRequired(attrs),
        options: options,
      ));
    }

    if (fields.isEmpty) {
      // Fallback default lead fields if the markup carries no recognisable fields
      fields.addAll(const [
        LeadFormField(name: 'name', label: 'Full Name', required: true),
        LeadFormField(name: 'email', label: 'Email', type: 'email', required: true),
        LeadFormField(name: 'phone', label: 'Phone Number', type: 'tel'),
      ]);
    }

    final submitText = _text(_submitButtonRe.firstMatch(html)?.group(1) ?? '');

    return FormPayload(
      introMessage: intro.isEmpty ? 'Silakan lengkapi form berikut:' : intro,
      fields: fields,
      webhookUrl: webhookUrl,
      submitLabel: submitText.isEmpty ? 'Submit' : submitText,
    );
  }

  Map<String, dynamic> toJson() => {
        'introMessage': introMessage,
        'fields': fields.map((f) => f.toJson()).toList(),
        'webhookUrl': webhookUrl,
        'submitLabel': submitLabel,
      };
}
